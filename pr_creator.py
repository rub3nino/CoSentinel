import os
import json
import re
import hashlib
import base64
import requests
from models import Finding
from fix_patches import apply_unified_diff, can_fix, validate_patch


def create_fix_pr(repo_url: str, github_token: str, finding_ids: list[str], all_findings: list[Finding]) -> str:
    """
    Creates a GitHub PR with auto-fixes for the specified finding_ids.
    Returns the PR URL.
    Raises RuntimeError on failure.
    """
    if not github_token:
        raise RuntimeError("GitHub token required to create PRs")

    owner, repo = _parse_repo(repo_url)
    headers = {
        "Authorization": f"Bearer {github_token}",
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
    }
    base_url = f"https://api.github.com/repos/{owner}/{repo}"

    fixable = [f for f in all_findings if f.id in finding_ids and can_fix(f)]
    if not fixable:
        raise RuntimeError("No auto-fixable findings with validated patches found")

    repo_info = _gh(f"{base_url}", headers)
    default_branch = repo_info.get("default_branch", "main")

    ref_data = _gh(f"{base_url}/git/ref/heads/{default_branch}", headers)
    base_sha = ref_data["object"]["sha"]

    branch_name = _branch_name(repo_url, fixable)
    try:
        _gh_post(f"{base_url}/git/refs", headers, {
            "ref": f"refs/heads/{branch_name}",
            "sha": base_sha,
        })
    except Exception:
        _gh_patch(f"{base_url}/git/refs/heads/{branch_name}", headers, {
            "sha": base_sha,
            "force": True,
        })

    applied = 0
    for finding in fixable:
        if not finding.file_path or not finding.fix_patch:
            continue
        try:
            if _apply_patch_commit(base_url, headers, branch_name, finding):
                applied += 1
        except Exception:
            pass

    if applied == 0:
        raise RuntimeError("No patches could be applied to create a PR")

    body_lines = [
        "## CoSentinel Auto-Fix PR",
        "",
        "This PR was automatically generated by CoSentinel to fix security vulnerabilities.",
        "",
        "### Fixed Issues",
        "",
    ]
    for f in fixable:
        body_lines.append(f"- **[{f.id}]** {f.title} — `{f.file_path}`")
    body_lines += [
        "",
        "### Review Checklist",
        "- [ ] Review each change for correctness",
        "- [ ] Run tests after merging",
        "- [ ] Rotate any exposed credentials manually",
        "",
        "_Generated by CoSentinel — AI-powered security scanner_",
    ]

    try:
        pr = _gh_post(f"{base_url}/pulls", headers, {
            "title": f"[CoSentinel] Fix {applied} security issue(s)",
            "body": "\n".join(body_lines),
            "head": branch_name,
            "base": default_branch,
        })
        return pr["html_url"]
    except RuntimeError as exc:
        if "422" in str(exc) and "A pull request already exists" in str(exc):
            try:
                prs = _gh(f"{base_url}/pulls?head={owner}:{branch_name}&state=open", headers)
                if prs:
                    return prs[0]["html_url"]
            except Exception:
                pass
        raise


def _parse_repo(url: str) -> tuple[str, str]:
    url = url.rstrip("/").removesuffix(".git")
    m = re.search(r"(?:github\.com[:/])([^/]+)/([^/]+)$", url)
    if not m:
        raise ValueError(f"Not a GitHub URL: {url}")
    return m.group(1), m.group(2)


def _gh(url: str, headers: dict) -> dict:
    r = requests.get(url, headers=headers, timeout=15)
    if not r.ok:
        raise RuntimeError(f"GitHub GET {url} failed: {r.status_code} {r.text[:300]}")
    return r.json()


def _gh_post(url: str, headers: dict, body: dict) -> dict:
    r = requests.post(url, headers=headers, json=body, timeout=15)
    if not r.ok:
        raise RuntimeError(f"GitHub POST {url} failed: {r.status_code} {r.text[:300]}")
    return r.json()


def _gh_patch(url: str, headers: dict, body: dict) -> dict:
    r = requests.patch(url, headers=headers, json=body, timeout=15)
    if not r.ok:
        raise RuntimeError(f"GitHub PATCH {url} failed: {r.status_code} {r.text[:300]}")
    return r.json()


def _apply_patch_commit(base_url: str, headers: dict, branch: str, finding: Finding) -> bool:
    file_path = finding.file_path
    if not file_path or not finding.fix_patch:
        return False

    file_data = _gh(f"{base_url}/contents/{file_path}?ref={branch}", headers)
    current_content = base64.b64decode(file_data["content"]).decode("utf-8")
    file_sha = file_data["sha"]

    if not validate_patch(current_content, finding.fix_patch):
        return False

    new_content = apply_unified_diff(current_content, finding.fix_patch)
    if new_content is None or new_content == current_content:
        return False

    encoded = base64.b64encode(new_content.encode("utf-8")).decode("ascii")
    _gh_post(f"{base_url}/contents/{file_path}", headers, {
        "message": f"fix({finding.id}): {finding.title}",
        "content": encoded,
        "sha": file_sha,
        "branch": branch,
    })
    return True


def _branch_name(repo_url: str, findings: list[Finding]) -> str:
    seed = repo_url + "|" + "|".join(sorted(f.id for f in findings))
    digest = hashlib.sha1(seed.encode("utf-8")).hexdigest()[:10]
    return f"cosentinel-auto-fix-{digest}"
