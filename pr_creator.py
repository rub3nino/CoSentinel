import os
import json
import re
import hashlib
import requests
from models import Finding


def create_fix_pr(repo_url: str, github_token: str, finding_ids: list[str], all_findings: list[Finding]) -> str:
    """
    Creates a GitHub PR with auto-fixes for the specified finding_ids.
    Returns the PR URL.
    Raises RuntimeError on failure.
    """
    if not github_token:
        raise RuntimeError("GitHub token required to create PRs")

    # Parse owner/repo from URL
    owner, repo = _parse_repo(repo_url)
    headers = {
        "Authorization": f"Bearer {github_token}",
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
    }
    base_url = f"https://api.github.com/repos/{owner}/{repo}"

    # Filter to fixable findings
    fixable = [f for f in all_findings if f.id in finding_ids and _can_fix(f)]
    if not fixable:
        raise RuntimeError("No auto-fixable findings with patches found")

    # Get default branch
    repo_info = _gh(f"{base_url}", headers)
    default_branch = repo_info.get("default_branch", "main")

    # Get SHA of default branch tip
    ref_data = _gh(f"{base_url}/git/ref/heads/{default_branch}", headers)
    base_sha = ref_data["object"]["sha"]

    # Create fix branch
    branch_name = _branch_name(repo_url, fixable)
    try:
        _gh_post(f"{base_url}/git/refs", headers, {
            "ref": f"refs/heads/{branch_name}",
            "sha": base_sha,
        })
    except Exception:
        _gh_patch(f"{base_url}/git/refs/heads/{branch_name}", headers, {
            "sha": base_sha,
            "force": True,
        })

    # Apply each fix patch as a separate commit
    applied = 0
    for finding in fixable:
        if not finding.file_path or not finding.fix_patch:
            continue
        try:
            if _apply_patch_commit(base_url, headers, branch_name, finding):
                applied += 1
        except Exception:
            pass  # skip failed patches, still create PR with what worked

    if applied == 0:
        raise RuntimeError("No patches could be applied to create a PR")

    # Build PR body
    body_lines = [
        "## CoSentinel Auto-Fix PR",
        "",
        "This PR was automatically generated by [CoSentinel](https://github.com) to fix security vulnerabilities.",
        "",
        "### Fixed Issues",
        "",
    ]
    for f in fixable:
        body_lines.append(f"- **[{f.id}]** {f.title} — `{f.file_path}`")
    body_lines += [
        "",
        "### Review Checklist",
        "- [ ] Review each change for correctness",
        "- [ ] Run tests after merging",
        "- [ ] Rotate any exposed credentials manually",
        "",
        "_Generated by CoSentinel — AI-powered security scanner_",
    ]

    pr = _gh_post(f"{base_url}/pulls", headers, {
        "title": f"[CoSentinel] Fix {len(fixable)} security issue(s)",
        "body": "\n".join(body_lines),
        "head": branch_name,
        "base": default_branch,
    })
    return pr["html_url"]


def _parse_repo(url: str) -> tuple[str, str]:
    url = url.rstrip("/").removesuffix(".git")
    parts = url.split("github.com/")
    if len(parts) != 2:
        raise ValueError(f"Not a GitHub URL: {url}")
    segments = parts[1].split("/")
    if len(segments) < 2:
        raise ValueError(f"Cannot parse owner/repo from: {url}")
    return segments[0], segments[1]


def _gh(url: str, headers: dict) -> dict:
    r = requests.get(url, headers=headers, timeout=15)
    r.raise_for_status()
    return r.json()


def _gh_post(url: str, headers: dict, body: dict) -> dict:
    r = requests.post(url, headers=headers, json=body, timeout=15)
    r.raise_for_status()
    return r.json()


def _gh_patch(url: str, headers: dict, body: dict) -> dict:
    r = requests.patch(url, headers=headers, json=body, timeout=15)
    r.raise_for_status()
    return r.json()


def _apply_patch_commit(base_url: str, headers: dict, branch: str, finding: Finding) -> None:
    """Apply fix_patch as a file update commit on the branch."""
    file_path = finding.file_path

    # Get current file content + SHA
    file_data = _gh(f"{base_url}/contents/{file_path}?ref={branch}", headers)
    import base64
    current_content = base64.b64decode(file_data["content"]).decode("utf-8")
    file_sha = file_data["sha"]

    # Apply patch (simple line replacement — fix_patch is unified diff format)
    if finding.fix_patch:
        new_content = _apply_unified_diff(current_content, finding.fix_patch)
    else:
        new_content = _synthesize_fix(current_content, finding)
    if new_content == current_content:
        return False

    encoded = base64.b64encode(new_content.encode("utf-8")).decode("ascii")
    _gh_post(f"{base_url}/contents/{file_path}", headers, {
        "message": f"fix({finding.id}): {finding.title}",
        "content": encoded,
        "sha": file_sha,
        "branch": branch,
    })
    return True


def _synthesize_fix(content: str, finding: Finding) -> str:
    title = finding.title
    if title in {"Hardcoded Bind All", "Hardcoded Bind All detected"}:
        return content.replace("0.0.0.0", "127.0.0.1")
    if title in {"Exposed on all interfaces", "Exposed on all interfaces detected"}:
        return content.replace("0.0.0.0", "127.0.0.1")
    if title in {"Debug Mode", "Debug Mode detected"}:
        return content.replace("debug=True", "debug=False").replace("debug = True", "debug = False")
    if title in {"Privileged Container", "Privileged mode hint", "Privileged Container detected", "Privileged mode hint detected"}:
        lines = [line for line in content.splitlines(keepends=True) if "privileged: true" not in line and "--privileged" not in line]
        return "".join(lines)
    if title in {"World Writable", "World Writable detected"}:
        return content.replace("chmod 777", "chmod 755").replace("chmod a+w", "chmod u+w").replace("chmod o+w", "chmod u+w")
    if title in {"Unquoted Variable", "Unquoted Variable detected"}:
        return re.sub(r"\[\s+\$([A-Za-z_][A-Za-z0-9_]*)\s+([=!])", r'[ "$\1" \2', content)
    if title in {"TLS Skip Verify", "TLS Skip Verify detected"}:
        return content.replace("InsecureSkipVerify: true", "InsecureSkipVerify: false")
    return content


def _can_fix(finding: Finding) -> bool:
    if finding.auto_fixable and finding.fix_patch:
        return True
    return finding.title in {
        "Hardcoded Bind All",
        "Exposed on all interfaces",
        "Debug Mode",
        "Privileged Container",
        "Privileged mode hint",
        "World Writable",
        "Unquoted Variable",
        "TLS Skip Verify",
    }


def _branch_name(repo_url: str, findings: list[Finding]) -> str:
    seed = repo_url + "|" + "|".join(sorted(f.id for f in findings))
    digest = hashlib.sha1(seed.encode("utf-8")).hexdigest()[:10]
    return f"cosentinel/auto-fix-{digest}"


def _apply_unified_diff(content: str, patch: str) -> str:
    """Minimal unified diff applier for single-file patches."""
    lines = content.splitlines(keepends=True)
    result = []
    patch_lines = patch.splitlines()
    i = 0
    src_line = 0

    while i < len(patch_lines):
        line = patch_lines[i]
        if line.startswith("@@"):
            # Parse @@ -start,count +start,count @@
            import re
            m = re.search(r"@@ -(\d+)(?:,\d+)? \+(\d+)", line)
            if m:
                src_start = int(m.group(1)) - 1
                # copy unchanged lines up to this hunk
                result.extend(lines[src_line:src_start])
                src_line = src_start
        elif line.startswith("-"):
            src_line += 1  # skip removed line
        elif line.startswith("+"):
            result.append(line[1:] + ("\n" if not line[1:].endswith("\n") else ""))
        elif line.startswith(" "):
            result.extend(lines[src_line:src_line + 1])
            src_line += 1
        i += 1

    result.extend(lines[src_line:])
    return "".join(result)
